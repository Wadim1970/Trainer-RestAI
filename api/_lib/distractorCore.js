// Дистракторы для упражнений уровня 1 — БЕЗ ИИ и без данных других клиентов
// (правило: меню чужих ресторанов в обучении не используем).
//   • «почти правильные»: в названии блюда меняем основной продукт
//     («Цезарь с курицей» → «Цезарь с креветками»);
//   • общий обезличенный каталог типовых названий по категориям.
// Всё, что совпало с настоящим блюдом меню, отбрасывается.

export const norm = (s) => String(s ?? '').trim().toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim()

const SWAPS = [
  ['курицей', 'креветками'], ['креветками', 'курицей'], ['лососем', 'тунцом'], ['тунцом', 'лососем'],
  ['говядиной', 'бараниной'], ['бараниной', 'говядиной'], ['свининой', 'индейкой'], ['индейкой', 'свининой'],
  ['грибами', 'шпинатом'], ['шпинатом', 'грибами'], ['беконом', 'ветчиной'], ['ветчиной', 'беконом'],
  ['уткой', 'гусем'], ['карамелью', 'шоколадом'], ['шоколадом', 'карамелью'], ['малиной', 'вишней'], ['вишней', 'малиной'],
  ['куриный', 'утиный'], ['куриная', 'утиная'], ['грибной', 'овощной'], ['грибная', 'овощная'],
  ['мясной', 'рыбный'], ['мясная', 'рыбная'], ['сливочный', 'томатный'], ['томатный', 'сливочный'],
  ['сливочная', 'томатная'], ['томатная', 'сливочная'], ['куриное', 'утиное'], ['овощное', 'грибное'],
]

// «Почти правильные» варианты названия (может быть пусто).
export function nearMisses(name) {
  const out = []
  const words = String(name).split(/(\s+)/)
  for (const [from, to] of SWAPS) {
    const i = words.findIndex((w) => norm(w) === from)
    if (i < 0) continue
    const w = words[i]
    const swapped = w[0] === w[0].toUpperCase() && w[0] !== w[0].toLowerCase() ? to[0].toUpperCase() + to.slice(1) : to
    out.push(words.map((x, n) => (n === i ? swapped : x)).join(''))
  }
  return out
}

