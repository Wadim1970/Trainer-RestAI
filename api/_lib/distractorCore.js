const ROLE_HINTS = [
  [/салат/, 'salad'], [/суп|бульон/, 'soup'], [/закуск|антипаст|холодн/, 'starter'], [/горяч|основн|мясо|рыб|стейк|гриль|паста|пицц/, 'main'],
  [/гарнир/, 'side'], [/десерт|сладк/, 'dessert'], [/безалког|лимонад|сок|вода/, 'soft'], [/кофе|чай|горячие напитки/, 'hot_drink'], [/алког|вино|коктейл|пиво|виски|водка/, 'alco'],
]
export const ROLES = Object.keys(CATALOG)

// Роль блюда: заданная в меню (course_role) или по названию раздела.
export function roleOf(row) {
  if (row.course_role && CATALOG[row.course_role]) return row.course_role
  const s = norm(row.menu_section || row.section)
  for (const [re, role] of ROLE_HINTS) if (re.test(s)) return role
  return 'other'
}

// n дистракторов для блюда: до двух «почти правильных», затем каталог той же
// роли, затем остальной каталог. realNames — названия всего меню (их исключаем).
export function distractorsFor(dish, realNames, n, rng) {
  const taken = new Set(realNames.map(norm))
  const near = []
  const pool = []
  const tryAdd = (name, list) => {
    const k = norm(name)
    if (!k || taken.has(k)) return
    // Название, содержащее настоящее блюдо целиком (или наоборот), сбивает с толку — пропускаем.
    for (const real of taken) if (real.length > 5 && (k.includes(real) || real.includes(k))) return
    taken.add(k)
    list.push(name)
  }
  for (const m of nearMisses(dish.name)) tryAdd(m, near)
  const sameRole = shuffle([...(CATALOG[dish.role] || [])], rng)
  const otherRoles = shuffle(ROLES.filter((r) => r !== dish.role).flatMap((r) => CATALOG[r]), rng)
  for (const c of [...sameRole, ...otherRoles]) tryAdd(c, pool)
  return [...near.slice(0, 2), ...pool].slice(0, n)
}

export function shuffle(arr, rng) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

// Детерминированный генератор (для тестов и воспроизводимых сессий).
export function seeded(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
